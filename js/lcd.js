function textWidth(str) {
  let w = 0;
  for (const ch of String(str).toUpperCase()) { const f = FONT[ch] || FONT["?"]; w += f.w + 1; }
  return Math.max(0, w - 1);
}
function text(str, x, y) {
  let cx = x | 0;
  for (const ch of String(str).toUpperCase()) {
    const f = FONT[ch] || FONT["?"];
    for (let r = 0; r < 7; r++) {
      const row = f.bits[r];
      for (let c = 0; c < f.w; c++) if (row[c] === "#") px(cx + c, y + r);
    }
    cx += f.w + 1;
  }
}
function textC(str, cy) { return text(str, Math.max(0, ((LCD.W - textWidth(str)) / 2) | 0), cy); }
/* scaled-up text (2x) for the standby clock */
function textBig(str, x, y) {
  let cx = x | 0;
  for (const ch of String(str).toUpperCase()) {
    const f = FONT[ch] || FONT["?"];
    for (let r = 0; r < 7; r++) {
      const row = f.bits[r];
      for (let c = 0; c < f.w; c++) if (row[c] === "#") rect(cx + c * 2, y + r * 2, 2, 2);
    }
    cx += (f.w + 1) * 2;
  }
}
function textBigW(str) { return textWidth(str) * 2 - 2; }

