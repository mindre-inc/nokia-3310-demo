/* ---------------- status widgets ---------------- */
function signalBars(x, y, level) { // level 0..4, 8px wide, 6px tall
  for (let i = 0; i < 4; i++) {
    const h = 2 + i * 1;
    if (i < level) rect(x + i * 2, y + 6 - h, 1, h);
  }
}
function batteryIcon(x, y, pct) { // x,y top-left; 9px wide, 7px tall
  hollowRect(x, y, 8, 6); rect(x + 8, y + 2, 1, 2);
  const bars = Math.max(0, Math.min(4, Math.round(pct / 25)));
  for (let i = 0; i < bars; i++) rect(x + 1 + i * 2, y + 1, 1, 4);
}

/* ---------------- screen chrome helpers ---------------- */
function titleBar(str) { // top row: title centered-ish, used by list screens
  text(str, 1, 0);
  lineH(0, 8, LCD.W);
}
/* Soft-key row — MIN-40 single-centre-option layout.
 *
 * The 3310 has exactly ONE general-purpose key: the Navi/select button in
 * the CENTRE under the display. Its function is the single word shown at
 * the BOTTOM-CENTRE of the screen — the only "button alternative" the
 * screen ever offers.
 *
 * The C key (clear/back) and the scroll rocker (up/down) are FIXED-FUNCTION
 * keys with implicit behaviour: they never get on-screen labels, so no
 * phantom left/right soft-key buttons are implied by the layout.
 */
function softRow(center) {
  if (center == null) return;
  textC(center, LCD.H - 7);
}
function sepRow(y) { lineH(0, y, LCD.W); }
